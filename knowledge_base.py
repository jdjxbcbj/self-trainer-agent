    def get_method(self, constraint: str, strategy_name: str) -> dict:
        """
        按「约束ID + 策略中文名」返回一条方法论内容。

        参数:
            constraint: 约束ID，4 档之一：want_maintain / endure_but_record /
                        dont_care / want_cutoff
            strategy_name: 策略中文名，如 "转移话题" / "软边界表达"

        返回:
            dict: {"title", "when", "how", "why", "example"} 五要素。
                  命中硬编码数据时返回完整内容；
                  未命中时返回通用兜底内容，并打印日志说明。
        """
        # 步骤1：尝试按「约束ID + 策略名」查完整内容
        method = self._METHODS.get(constraint, {}).get(strategy_name)

        if method is None:
            # 未命中：策略名不在硬编码数据中（可能是该约束的第 3、4 个策略，
            # 或约束ID本身非法）。返回通用兜底，保证调用方拿到的结构永远完整。
            print(f"[KnowledgeBase] 未命中，使用兜底：constraint={constraint}, "
                  f"strategy_name={strategy_name}")
            return {
                "title": strategy_name,
                "when": "（通用）对方在施加压力时",
                "how": "结合当前约束目标回应",
                "why": "避免正面冲突同时守住底线",
                "example": "请结合具体场景",
            }

        # 步骤2：命中，返回完整内容。title 直接用策略名，避免与数据 key 不一致。
        print(f"[KnowledgeBase] 命中方法论：constraint={constraint}, "
              f"strategy_name={strategy_name}")
        # 拷贝一份再改，避免外部拿到引用后误改内部数据
        result = dict(method)
        result["title"] = strategy_name
        return result

    def get_legal(self, scenario_id: str) -> list:
        """
        返回该场景相关法条文本列表（list[str]）。

        参数:
            scenario_id: 场景ID，例如 "wang_ayi_cuihun"

        返回:
            list[str]: 法条文本列表。场景无对应法条时返回空列表（不抛异常）。
        """
        # 查不到场景时返回空列表，而非抛异常——法条是「锦上添花」的辅助内容，
        # 缺了不该打断主流程。
        legal = self._LEGAL.get(scenario_id, [])
        print(f"[KnowledgeBase] 获取法条：scenario_id={scenario_id}, "
              f"命中 {len(legal)} 条")
        # 返回副本，隔离内部数据
        return list(legal)
