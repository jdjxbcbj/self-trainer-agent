    def __init__(self):
        # 场景库是法条的唯一真源，get_legal 委托它取数据。
        self._scenario_store = ScenarioStore()

    def get_method(self, scenario_id: str, strategy: str) -> dict:
        """
        按「场景ID + 招式中文名」返回一条方法论内容。

        参数:
            scenario_id: 场景ID，例如 "neighbor-noise"。本期主要用于日志与
                         未来的场景化差异，命中内容时不影响返回结构。
            strategy: 招式中文名，取 GSB 7 个正向维度中文名之一：
                      表达边界 / 保持冷静 / 合规合法 / 降温控场 /
                      取证意识 / 礼貌 / 求助意识。

        返回:
            dict: {"title", "when", "how", "why", "example"} 五要素。
                  命中硬编码数据时返回完整内容；
                  招式名不在 7 招之内时返回通用兜底内容（title == strategy 本身），不抛异常。
        """
        # 步骤1：记录请求，并按招式名查完整内容
        print(f"[KnowledgeBase] 步骤1 - 请求方法论：scenario_id={scenario_id}, "
              f"strategy={strategy}")
        method = self._METHODS.get(strategy)

        if method is None:
            # 未命中：招式名不在 7 招之内。返回通用安全提示兜底，
            # 保证调用方拿到的结构永远完整、不抛异常。
            print(f"[KnowledgeBase] 步骤2 - 未命中 7 招，使用通用安全兜底：strategy={strategy}")
            return {
                "title": strategy,
                "when": "对方施压、场面可能出现冲突时",
                "how": "保持冷静、说清边界，必要时保留记录并向第三方求助",
                "why": "避免正面冲突升级，保护自己",
                "example": "请结合具体场景，使用「表达边界、保持冷静、合规合法」等招式回应",
            }

        # 步骤2：命中，返回完整内容。title 直接用招式名，避免与数据 key 不一致。
        print(f"[KnowledgeBase] 步骤2 - 命中方法论：scenario_id={scenario_id}, "
              f"strategy={strategy}")
        # 深拷贝再改，避免外部拿到引用后误改内部数据。
        result = copy.deepcopy(method)
        result["title"] = strategy
        return result

    def get_legal(self, scenario_id: str) -> list:
        """
        返回该场景相关法条文本列表（list[str]）。

        参数:
            scenario_id: 场景ID，例如 "neighbor-noise"

        返回:
            list[str]: 法条文本列表。场景不存在时返回空列表（不抛异常）。

        说明:
            法条的唯一真源是 scenario_store 每个场景的 laws 字段，这里委托
            ScenarioStore().get_scenario(scenario_id)["laws"] 返回，
            不自己再抄一份，避免两处数据漂移。
        """
        # 步骤1：请求场景法条
        print(f"[KnowledgeBase] 步骤1 - 请求场景法条：scenario_id={scenario_id}")
        try:
            scenario = self._scenario_store.get_scenario(scenario_id)
        except KeyError:
            # 场景不存在：法条是「锦上添花」的辅助内容，缺了不该打断主流程。
            print(f"[KnowledgeBase] 步骤2 - 场景不存在，返回空列表：scenario_id={scenario_id}")
            return []

        # 步骤2：取该场景 laws 字段并返回副本，隔离内部数据。
        laws = scenario["laws"]
        print(f"[KnowledgeBase] 步骤2 - 命中 {len(laws)} 条法条：scenario_id={scenario_id}")
        return list(laws)
